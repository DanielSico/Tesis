# FASTA READER
# ============================================================

def read_fasta(path):

    header = None

    sequence = []

    with open(
        path,
        "r",
        encoding="utf-8"
    ) as handle:

        for line in handle:

            line = line.strip()

            if not line:

                continue

            if line.startswith(">"):

                if header is not None:

                    yield (
                        header,
                        "".join(
                            sequence
                        ).upper()
                    )

                header = (
                    line[1:]
                )

                sequence = []

            else:

                sequence.append(
                    line
                )

        if header is not None:

            yield (
                header,
                "".join(
                    sequence
                ).upper()
            )


# ============================================================
# CDS VALIDATION
# ============================================================

def validate_cds(sequence):

    length = len(
        sequence
    )

    # --------------------------------------------------------
    # 1. Length divisible by 3
    # --------------------------------------------------------

    if length % 3 != 0:

        return (
            False,
            "length_not_divisible_by_3",
            0
        )

    # --------------------------------------------------------
    # 2. Initial ATG
    # --------------------------------------------------------

    if sequence[:3] != "ATG":

        return (
            False,
            "missing_initial_ATG",
            0
        )

    # --------------------------------------------------------
    # 3. Terminal stop codon
    # --------------------------------------------------------

    if sequence[-3:] not in STOP_CODONS:

        return (
            False,
            "missing_terminal_stop",
            0
        )

    codons = [

        sequence[i:i + 3]

        for i in range(
            0,
            length,
            3
        )
    ]

    # --------------------------------------------------------
    # 4. No internal stop codons
    # --------------------------------------------------------

    for codon in codons[:-1]:

        if codon in STOP_CODONS:

            return (
                False,
                "internal_stop_codon",
                0
            )

    # --------------------------------------------------------
    # 5. At least 150 sense codons
    # --------------------------------------------------------

    sense_codon_count = (

        length // 3

    ) - 1

    if (
        sense_codon_count
        < MIN_SENSE_CODONS
    ):

        return (
            False,
            "fewer_than_150_sense_codons",
            sense_codon_count
        )

    return (
        True,
        "valid",
        sense_codon_count
    )


# ============================================================
# GENE IDENTIFICATION
# ============================================================

def get_gene_identifier(header):

    # --------------------------------------------------------
    # 1. GeneID
    # --------------------------------------------------------

    match = re.search(
        r"GeneID:(\d+)",
        header
    )

    if match:

        return (
            f"GeneID:{match.group(1)}",
            "GeneID"
        )

    # --------------------------------------------------------
    # 2. locus_tag
    # --------------------------------------------------------

    match = re.search(
        r"\[locus_tag=([^\]]+)\]",
        header
    )

    if match:

        return (
            f"locus_tag:{match.group(1)}",
            "locus_tag"
        )

    # --------------------------------------------------------
    # 3. gene
    # --------------------------------------------------------

    match = re.search(
        r"\[gene=([^\]]+)\]",
        header
    )

    if match:

        return (
            f"gene:{match.group(1)}",
            "gene"
        )

    return (
        None,
        None
    )


# ============================================================
# CODON COUNTING
# ============================================================

def count_sense_codons(sequence):

    # --------------------------------------------------------
    # Remove terminal stop codon
    # --------------------------------------------------------

    sense_sequence = (
        sequence[:-3]
    )

    codon_counts = {

        codon: 0

        for codon in SENSE_CODONS
    }

    for i in range(
        0,
        len(
            sense_sequence
        ),
        3
    ):

        codon = (
            sense_sequence[
                i:i + 3
            ]
        )

        if codon not in codon_counts:

            raise ValueError(
                f"Unsupported codon '{codon}' "
                "encountered after CDS validation."
            )

        codon_counts[
            codon
        ] += 1

    sense_codon_count = (

        len(
            sense_sequence
        )

        // 3
    )

    if (
        sum(
            codon_counts.values()
        )
        != sense_codon_count
    ):

        raise ValueError(
            "Codon-count consistency "
            "check failed."
        )

    return (
        codon_counts,
        sense_codon_count
    )


# ============================================================
# POSITION-SPECIFIC NUCLEOTIDE FREQUENCIES
# ============================================================

def calculate_position_frequencies(
    codon_counts,
    sequence_length
):

    position_counts = [

        {
            base: 0
            for base in DNA_BASES
        },

        {
            base: 0
            for base in DNA_BASES
        },

        {
            base: 0
            for base in DNA_BASES
        },
    ]

    for (
        codon,
        count

    ) in codon_counts.items():

        if count == 0:

            continue

        position_counts[0][
            codon[0]
        ] += count

        position_counts[1][
            codon[1]
        ] += count

        position_counts[2][
            codon[2]
        ] += count

    position_frequencies = []

    for position in position_counts:

        frequencies = {

            base:

                position[
                    base
                ]

                / sequence_length

            for base in DNA_BASES
        }

        position_frequencies.append(
            frequencies
        )

    return (
        position_frequencies
    )


# ============================================================
# DCBS
# ============================================================

def calculate_dcbs(
    codon_counts,
    sequence_length
):

    position_frequencies = (
        calculate_position_frequencies(
            codon_counts,
            sequence_length
        )
    )

    weighted_dcb_sum = 0.0

    for (
        codon,
        count

    ) in codon_counts.items():

        # ----------------------------------------------------
        # Absent codons do not contribute
        # ----------------------------------------------------

        if count == 0:

            continue

        observed_frequency = (

            count

            / sequence_length
        )

        expected_frequency = (

            position_frequencies[0][
                codon[0]
            ]

            * position_frequencies[1][
                codon[1]
            ]

            * position_frequencies[2][
                codon[2]
            ]
        )

        if expected_frequency <= 0:

            raise ValueError(
                f"Expected frequency for "
                f"observed codon {codon} "
                "is zero."
            )

        dcb = max(

            observed_frequency
            / expected_frequency,

            expected_frequency
            / observed_frequency
        )

        weighted_dcb_sum += (

            count

            * dcb
        )

    return (

        weighted_dcb_sum

        / sequence_length
    )


# ============================================================
# CODON / ANTICODON CONVERSION
# ============================================================

def dna_codon_to_rna(codon):

    return (

        codon
        .upper()
        .replace(
            "T",
            "U"
        )
    )


def reverse_complement_rna(
    codon_dna
):

    codon_rna = (
        dna_codon_to_rna(
            codon_dna
        )
    )

    return "".join(

        RNA_COMPLEMENT[
            base
        ]

        for base in reversed(
            codon_rna
        )
    )


# ============================================================
# tRNA TEXT PARSER
# ============================================================

TRNA_PAIR_PATTERN = re.compile(

    r"""
    (?<![A-Za-z])
    ([ACGTUacgtu]{3})
    (?![A-Za-z])
    \s*
    [,;:\t|]?
    \s*
    ([+-]?\d+(?:\.0+)?)
    """,

    re.VERBOSE
)


def read_trna_table(path):

    path = Path(
        path
    )

    text = (
        path.read_text(
            encoding="utf-8-sig"
        )
    )

    matches = list(

        TRNA_PAIR_PATTERN.finditer(
            text
        )
    )

    if not matches:

        raise ValueError(
            "No codon/count pairs were "
            "detected in the tRNA file."
        )

    trna_counts = {

        codon: 0

        for codon in ALL_CODONS
    }

    observed_codons = set()

    for match in matches:

        codon = (

            match.group(1)
            .upper()
            .replace(
                "U",
                "T"
            )
        )

        numeric_count = float(
            match.group(2)
        )

        if not (
            numeric_count.is_integer()
        ):

            raise ValueError(
                f"Non-integer tRNA copy "
                f"number for {codon}: "
                f"{numeric_count}"
            )

        copies = int(
            numeric_count
        )

        if copies < 0:

            raise ValueError(
                f"Negative tRNA copy "
                f"number for {codon}: "
                f"{copies}"
            )

        trna_counts[
            codon
        ] += copies

        observed_codons.add(
            codon
        )

    return (
        trna_counts,
        len(matches),
        len(
            observed_codons
        )
    )


# ============================================================
# A34 EDITING SETTINGS
# ============================================================

def get_a34_candidates(
    mode,
    custom_candidates
):

    if custom_candidates:

        candidates = set()

        for value in (
            custom_candidates.split(
                ","
            )
        ):

            anticodon = (

                value
                .strip()
                .upper()
                .replace(
                    "T",
                    "U"
                )
            )

            if (
                len(
                    anticodon
                )
                != 3

                or any(
                    base not in "ACGU"
                    for base in anticodon
                )

                or anticodon[0] != "A"
            ):

                raise ValueError(
                    f"Invalid A34 candidate: "
                    f"{anticodon}"
                )

            candidates.add(
                anticodon
            )

        return candidates

    if mode == "eukaryotic":

        return set(
            EUKARYOTIC_A34_CANDIDATES
        )

    if mode == "bacterial":

        return set(
            BACTERIAL_A34_CANDIDATES
        )

    if mode == "none":

        return set()

    raise ValueError(
        f"Unsupported A34 mode: "
        f"{mode}"
    )


# ============================================================
# WOBBLE PAIRING RULES
# ============================================================

def wobble_pairing_rule(
    anticodon_position_34,
    codon_position_3
):

    pair = (
        anticodon_position_34,
        codon_position_3
    )

    # --------------------------------------------------------
    # Fixed zero-penalty interactions
    # --------------------------------------------------------

    fixed_zero_pairs = {

        ("A", "U"),
        ("G", "C"),
        ("U", "A"),
        ("C", "G"),
        ("I", "U"),
    }

    if pair in fixed_zero_pairs:

        return {

            "pair":
                f"{pair[0]}:{pair[1]}",

            "interaction_type":
                "unpenalized",

            "penalty_parameter":
                "fixed",

            "fixed_sij":
                0.0,
        }

    # --------------------------------------------------------
    # Optimized wobble interactions
    # --------------------------------------------------------

    wobble_parameters = {

        ("G", "U"):
            "s_GU",

        ("U", "G"):
            "s_UG",

        ("I", "C"):
            "s_IC",

        ("I", "A"):
            "s_IA",
    }

    if pair in wobble_parameters:

        return {

            "pair":
                f"{pair[0]}:{pair[1]}",

            "interaction_type":
                "wobble",

            "penalty_parameter":
                wobble_parameters[
                    pair
                ],

            "fixed_sij":
                None,
        }

    return None


# ============================================================
# CANONICAL PAIRING AT POSITIONS 1 AND 2
# ============================================================

def is_canonical_pair(
    anticodon_base,
    codon_base
):

    return (
        anticodon_base,
        codon_base
    ) in {

        ("A", "U"),
        ("U", "A"),

        ("G", "C"),
        ("C", "G"),
    }


# ============================================================
# CODON-tRNA COMPATIBILITY
# ============================================================

def build_trna_compatibility(
    trna_counts,
    a34_candidates
):

    compatibility_pairs = []

    source_trna_types = 0

    edited_trna_types = 0

    for (
        source_codon_dna,
        gene_copies

    ) in trna_counts.items():

        # ----------------------------------------------------
        # Stop codons are excluded
        # ----------------------------------------------------

        if (
            source_codon_dna
            in STOP_CODONS
        ):

            continue

        # ----------------------------------------------------
        # Count tRNA classes with copies
        # ----------------------------------------------------

        if gene_copies > 0:

            source_trna_types += 1

        source_amino_acid = (
            GENETIC_CODE[
                source_codon_dna
            ]
        )

        encoded_anticodon = (
            reverse_complement_rna(
                source_codon_dna
            )
        )

        effective_anticodon = (
            encoded_anticodon
        )

        a34_edited = False

        # ----------------------------------------------------
        # A34 -> I34
        # ----------------------------------------------------

        if (
            encoded_anticodon
            in a34_candidates
        ):

            effective_anticodon = (

                "I"

                + encoded_anticodon[
                    1:
                ]
            )

            a34_edited = True

            if gene_copies > 0:

                edited_trna_types += 1

        # ----------------------------------------------------
        # Test target sense codons
        # ----------------------------------------------------

        for (
            target_codon_dna

        ) in SENSE_CODONS:

            if (
                GENETIC_CODE[
                    target_codon_dna
                ]
                != source_amino_acid
            ):

                continue

            target_codon_rna = (
                dna_codon_to_rna(
                    target_codon_dna
                )
            )

            # ------------------------------------------------
            # Positions 1 and 2
            # ------------------------------------------------

            if not is_canonical_pair(

                effective_anticodon[2],

                target_codon_rna[0]
            ):

                continue

            if not is_canonical_pair(

                effective_anticodon[1],

                target_codon_rna[1]
            ):

                continue

            # ------------------------------------------------
            # Position 34 / codon position 3
            # ------------------------------------------------

            pairing = (
                wobble_pairing_rule(

                    effective_anticodon[0],

                    target_codon_rna[2]
                )
            )

            if pairing is None:

                continue

            compatibility_pairs.append({

                "source_codon_dna":
                    source_codon_dna,

                "trna_gene_copies":
                    gene_copies,

                "encoded_anticodon_rna":
                    encoded_anticodon,

                "effective_anticodon_rna":
                    effective_anticodon,

                "a34_edited":
                    a34_edited,

                "recognized_codon_dna":
                    target_codon_dna,

                "pairing":
                    pairing[
                        "pair"
                    ],

                "interaction_type":
                    pairing[
                        "interaction_type"
                    ],

                "penalty_parameter":
                    pairing[
                        "penalty_parameter"
                    ],

                "fixed_sij":
                    pairing[
                        "fixed_sij"
                    ],
            })

    return (
        compatibility_pairs,
        source_trna_types,
        edited_trna_types
    )


# ============================================================
# PRECOMPUTE Wi COMPONENTS
# ============================================================

def prepare_weight_components(
    compatibility_pairs
):
    """
    Precompute the copy-number contribution of each
    interaction class to every sense codon.

    This is equivalent to summing the compatibility
    pairs for every candidate sij set, but avoids
    repeating the same bookkeeping during thousands
    of optimization evaluations.
    """

    fixed_component = np.zeros(

        len(
            SENSE_CODONS
        ),

        dtype=float
    )

    wobble_components = {

        parameter:
            np.zeros(
                len(
                    SENSE_CODONS
                ),
                dtype=float
            )

        for parameter
        in PENALTY_NAMES
    }

    for pair in compatibility_pairs:

        codon_index = (
            CODON_INDEX[
                pair[
                    "recognized_codon_dna"
                ]
            ]
        )

        copies = float(
            pair[
                "trna_gene_copies"
            ]
        )

        parameter = (
            pair[
                "penalty_parameter"
            ]
        )

        if parameter == "fixed":

            fixed_component[
                codon_index
            ] += copies

        else:

            wobble_components[
                parameter
            ][
                codon_index
            ] += copies

    return (
        fixed_component,
        wobble_components
    )


# ============================================================
# Wi AND wi
# ============================================================

def calculate_codon_weights(
    fixed_component,
    wobble_components,
    penalties
):
    """
    Wi = sum_j [(1 - sij) * tGCN_ij]

    wi = Wi / max(Wi)
    """

    raw_weights = (
        fixed_component.copy()
    )

    for parameter in PENALTY_NAMES:

        raw_weights += (

            wobble_components[
                parameter
            ]

            * (
                1.0
                - penalties[
                    parameter
                ]
            )
        )

    maximum_weight = float(
        np.max(
            raw_weights
        )
    )

    if maximum_weight <= 0:

        raise ValueError(
            "All Wi values are zero."
        )

    relative_weights = (

        raw_weights

        / maximum_weight
    )

    zero_indices = np.where(

        relative_weights <= 0

    )[0]

    if (
        zero_indices.size
        > 0
    ):

        zero_codons = [

            SENSE_CODONS[
                index
            ]

            for index
            in zero_indices
        ]

        raise ValueError(

            "\nOne or more codons "
            "have wi = 0:\n"

            + ", ".join(
                zero_codons
            )

            + "\n\nlog(stAI) cannot "
              "be calculated without "
              "defining how zero weights "
              "are handled."
        )

    return (
        raw_weights,
        relative_weights
    )


# ============================================================
# SPEARMAN CORRELATION
# ============================================================

def calculate_spearman(
    dcbs_values,
    log_stai
):
    """
    Calculate Spearman rank correlation using SciPy.

    The optimization objective is the Spearman correlation
    between DCBS and log(stAI).
    """

    result = stats.spearmanr(
        dcbs_values,
        log_stai
    )

    rho = float(
        result.statistic
    )

    if not math.isfinite(
        rho
    ):

        raise ValueError(
            "Spearman correlation is undefined "
            "because one of the input variables "
            "has insufficient finite rank variation."
        )

    return rho


# ============================================================
# log(stAI)
# ============================================================

def calculate_log_stai(
    codon_count_matrix,
    sequence_lengths,
    relative_weights
):

    if np.any(
        relative_weights <= 0
    ):

        raise ValueError(
            "log(stAI) cannot be calculated "
            "because one or more wi values "
            "are zero."
        )

    log_weight_vector = (
        np.log(
            relative_weights
        )
    )

    weighted_log_sum = (

        codon_count_matrix

        @ log_weight_vector
    )

    return (

        weighted_log_sum

        / sequence_lengths
    )


# ============================================================
# EVALUATE ONE sij COMBINATION
# ============================================================

def evaluate_penalties(
    fixed_component,
    wobble_components,
    codon_count_matrix,
    sequence_lengths,
    dcbs_values,
    values
):

    penalties = dict(

        zip(
            PENALTY_NAMES,
            values
        )
    )

    (
        _,
        relative_weights

    ) = calculate_codon_weights(

        fixed_component,
        wobble_components,
        penalties
    )

    log_stai = (
        calculate_log_stai(

            codon_count_matrix,
            sequence_lengths,
            relative_weights
        )
    )

    # --------------------------------------------------------
    # stAI itself
    # --------------------------------------------------------

    stai = (
        np.exp(
            log_stai
        )
    )

    if not np.all(
        np.isfinite(
            stai
        )
    ):

        raise ValueError(
            "Non-finite stAI values "
            "were generated."
        )

    # --------------------------------------------------------
    # Optimization uses Spearman rho between DCBS
    # and log(stAI), calculated directly by SciPy.
    # --------------------------------------------------------

    rho = (
        calculate_spearman(
            dcbs_values,
            log_stai
        )
    )

    return rho


# ============================================================
# CACHED OBJECTIVE
# ============================================================

def make_objective(
    fixed_component,
    wobble_components,
    codon_count_matrix,
    sequence_lengths,
    dcbs_values
):

    cache = {}

    def objective(values):

        key = tuple(

            round(
                float(value),
                12
            )

            for value in values
        )

        if key not in cache:

            cache[
                key
            ] = evaluate_penalties(

                fixed_component,
                wobble_components,
                codon_count_matrix,
                sequence_lengths,
                dcbs_values,
                values
            )

        return (
            cache[
                key
            ]
        )

    return (
        objective,
        cache
    )


# ============================================================
# COARSE GRID SEARCH
# ============================================================

def run_grid_search(
    objective
):

    total_combinations = (

        len(
            GRID_VALUES
        )

        ** 4
    )

    best_values = None

    best_rho = (
        -math.inf
    )

    for (
        combination_number,
        values

    ) in enumerate(

        product(
            GRID_VALUES,
            repeat=4
        ),

        start=1
    ):

        rho = objective(
            values
        )

        if rho > best_rho:

            best_rho = (
                rho
            )

            best_values = (
                tuple(
                    values
                )
            )

        if (
            combination_number
            % 100
            == 0

            or combination_number
            == total_combinations
        ):

            print(
                f"  Grid search: "
                f"{combination_number}/"
                f"{total_combinations}"
            )

    return (
        best_values,
        best_rho
    )


# ============================================================
# LOCAL REFINEMENT
# ============================================================

def run_local_refinement(
    objective,
    initial_values,
    initial_rho
):
    """
    Deterministic variable-step hill climbing.

    At each step size, every valid combination of

        -step
         0
        +step

    across the four sij parameters is tested.

    Therefore, at most:

        3^4 - 1 = 80

    neighboring combinations are evaluated.

    The best improving neighbor becomes the new
    center. If no neighbor improves rho, the step
    is divided by 1.35.

    The process terminates when step < 0.001.
    """

    current_values = (
        np.array(
            initial_values,
            dtype=float
        )
    )

    current_rho = float(
        initial_rho
    )

    step = (
        REFINEMENT_INITIAL_STEP
    )

    evaluations = 0

    accepted_moves = 0

    print()

    print(
        "Starting local refinement..."
    )

    while (
        step
        >= REFINEMENT_MIN_STEP
    ):

        best_values = (
            current_values.copy()
        )

        best_rho = (
            current_rho
        )

        offsets = (
            -step,
            0.0,
            step
        )

        for delta in product(
            offsets,
            repeat=4
        ):

            if all(
                change == 0.0
                for change in delta
            ):

                continue

            candidate = (

                current_values

                + np.array(
                    delta,
                    dtype=float
                )
            )

            # ------------------------------------------------
            # sij bounds
            # ------------------------------------------------

            if np.any(
                candidate
                < MIN_SIJ
            ):

                continue

            if np.any(
                candidate
                > MAX_SIJ
            ):

                continue

            rho = objective(
                candidate
            )

            evaluations += 1

            if rho > best_rho:

                best_rho = (
                    rho
                )

                best_values = (
                    candidate.copy()
                )

        # ----------------------------------------------------
        # Improvement found:
        # keep same step and search again
        # ----------------------------------------------------

        if (
            best_rho
            > current_rho
        ):

            current_values = (
                best_values
            )

            current_rho = (
                best_rho
            )

            accepted_moves += 1

            print(
                f"  Improvement at step "
                f"{step:.9f}: "
                f"rho = "
                f"{current_rho:.10f}"
            )

        # ----------------------------------------------------
        # No improvement:
        # reduce step
        # ----------------------------------------------------

        else:

            step /= (
                REFINEMENT_STEP_FACTOR
            )

            print(
                f"  No improvement; "
                f"next step = "
                f"{step:.9f}"
            )

    return (

        tuple(
            float(value)
            for value
            in current_values
        ),

        current_rho,

        evaluations,

        accepted_moves,

        step
    )


