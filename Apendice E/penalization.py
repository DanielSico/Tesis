"""
penalization.py

Workflow
--------
1. Filter CDS sequences.
2. Retain the longest valid CDS per gene.
3. Remove terminal stop codons.
4. Count the 61 sense codons.
5. Calculate one DCBS value per CDS.
6. Read tRNA gene-copy counts from a plain-text file.
7. Build the codon-tRNA compatibility matrix.
8. Evaluate the 625 coarse sij combinations generated by:

       s_GU, s_UG, s_IC, s_IA in
       {0.0, 0.25, 0.50, 0.75, 0.9999}

9. Calculate Spearman correlation with scipy.stats.spearmanr.
10. Select the combination with the highest Spearman rho.
11. Refine that combination by hill climbing with progressively
    smaller steps.

INPUTS
------

-i / --input
    NCBI genomic CDS from an assembly.

-t / --trna
    Plain-text tRNA gene-copy-number table.

Refinement
----------
The local search starts with a step size of 0.3. At each step size,
all valid neighboring parameter sets produced by adding -step, 0,
or +step to each sij are evaluated. The best improving neighbor is
accepted. If no neighbor improves Spearman rho, the step is divided
by 1.35. Refinement stops when the next step is below 0.001.

No output files are created. Results are printed to the console only.
"""

